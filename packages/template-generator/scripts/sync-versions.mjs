#!/usr/bin/env node
/**
 * Keeps deps.ts + pnpm-workspace catalog + package manager pins aligned with versions.yaml.
 * Usage: node packages/template-generator/scripts/sync-versions.mjs [--check]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(PKG_ROOT, "../..");
const VERSIONS_YAML = path.join(PKG_ROOT, "versions.yaml");
const DEPS_TS = path.join(PKG_ROOT, "src/deps.ts");
const PINS_TS = path.join(PKG_ROOT, "src/package-manager-pins.generated.ts");

function loadManifest() {
  const raw = fs.readFileSync(VERSIONS_YAML, "utf8");
  /** @type {Record<string, unknown>} */
  const doc = parseYaml(raw);
  const pkg = doc.packages;
  const repoOnly = doc.repoOnly && typeof doc.repoOnly === "object" ? doc.repoOnly : {};
  const pm =
    doc.packageManagers && typeof doc.packageManagers === "object" ? doc.packageManagers : {};
  if (!pkg || typeof pkg !== "object") {
    throw new Error(`${VERSIONS_YAML}: missing packages: map`);
  }
  /** @type {Record<string,string>} */
  const mergedForCatalog = {
    .../** @type {Record<string,string>} */ (repoOnly),
    .../** @type {Record<string,string>} */ (pkg),
  };
  return {
    pkg: /** @type {Record<string,string>} */ (pkg),
    repoOnly: /** @type {Record<string,string>} */ (repoOnly),
    packageManagers: /** @type {Record<string,string>} */ (pm),
    mergedForCatalog,
  };
}

/** @returns {Iterable<string>} */
function* enumerateWorkspaceManifests(repoRoot) {
  const rootPg = path.join(repoRoot, "package.json");
  if (fs.existsSync(rootPg)) yield rootPg;

  const appsDir = path.join(repoRoot, "apps");
  if (fs.existsSync(appsDir)) {
    for (const name of fs.readdirSync(appsDir)) {
      const p = path.join(appsDir, name, "package.json");
      if (fs.existsSync(p)) yield p;
    }
  }

  const packagesDir = path.join(repoRoot, "packages");
  if (fs.existsSync(packagesDir)) {
    for (const name of fs.readdirSync(packagesDir)) {
      const p = path.join(packagesDir, name, "package.json");
      if (fs.existsSync(p)) yield p;
    }
  }
}

function collectWorkspaceCatalogDeps(repoRoot) {
  /** @type {Set<string>} */
  const need = new Set();
  for (const jsonPath of enumerateWorkspaceManifests(repoRoot)) {
    const j = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
    for (const kind of [
      "dependencies",
      "devDependencies",
      "optionalDependencies",
      "peerDependencies",
    ]) {
      const block = j[kind];
      if (!block || typeof block !== "object") continue;
      for (const [dep, ver] of Object.entries(block)) {
        if (ver === "catalog:") need.add(dep);
      }
    }
  }
  return [...need].sort((a, b) => a.localeCompare(b));
}

/** @type {(k: string) => string} */
function tsQuotedKey(key) {
  if (/^[A-Za-z_$][\w$]*$/.test(key)) return key;
  return JSON.stringify(key);
}

/**
 * @param {Record<string,string>} pkgs
 */
function renderDepsTs(pkgs) {
  const lines = Object.entries(pkgs).map(([k, v]) => `  ${tsQuotedKey(k)}: ${JSON.stringify(v)},`);

  return `/**
 * ╔══════════════════════════════════════════════════════════════════════════════╗
 * ║ AUTOGENERATED — do not edit by hand                                          ║
 * ║ Regenerate from packages/template-generator/versions.yaml via:               ║
 * ║   pnpm sync-versions                                                         ║
 * ╚══════════════════════════════════════════════════════════════════════════════╝
 *
 * Central version map consumed by scaffold handlers and Handlebars processors.
 */

export const DEPENDENCY_VERSIONS = {
${lines.join("\n")}
} as const satisfies Record<string, string>;

export type DependencyName = keyof typeof DEPENDENCY_VERSIONS;

export function version(name: DependencyName): string {
  const v = DEPENDENCY_VERSIONS[name];
  if (!v) {
    throw new Error(
      \`Dependency "\${String(name)}" not in central version map. Add it to versions.yaml.\`,
    );
  }
  return v;
}
`;
}

/** @param {Record<string,string>} pm */
function renderPinsTs(pm) {
  if (!pm.bun || !pm.pnpm || !pm.npm) {
    throw new Error("packageManagers.{bun,pnpm,npm} must be defined in versions.yaml");
  }
  const bun = pm.bun;
  const pnpm = pm.pnpm;
  const npm = pm.npm;
  return `/**
 * ╔══════════════════════════════════════════════════════════════════════════════╗
 * ║ AUTOGENERATED — do not edit by hand                                          ║
 * ║   pnpm sync-versions                                                         ║
 * ╚══════════════════════════════════════════════════════════════════════════════╝
 */

export function packageManagerSpecifier(pm: "bun" | "pnpm" | "npm"): string {
  switch (pm) {
    case "bun":
      return ${JSON.stringify(bun)};
    case "pnpm":
      return ${JSON.stringify(pnpm)};
    case "npm":
      return ${JSON.stringify(npm)};
    default:
      throw new Error(\`Unknown package manager: \${pm}\`);
  }
}
`;
}

/**
 * @param {Record<string,string>} sortedEntries
 */
function renderPnpmCatalogYaml(sortedEntries) {
  /** @type {string[]} */
  const lines = ["catalog:"];
  for (const [k, ver] of sortedEntries) {
    const needsQuote = k.startsWith("@") || k.includes(".") || !/^[A-Za-z0-9_-]+$/.test(k);
    const ks = needsQuote ? `"${String(k).replace(/"/g, '\\"')}"` : k;
    lines.push(`  ${ks}: ${String(ver).trim()}`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * @param {string} file
 * @param {string} content
 * @param {boolean} checkOnly
 */
function writeIfChanged(file, content, checkOnly) {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (prev === content) return false;
  if (checkOnly) {
    console.error(`[sync-versions] ✗ Divergence: ${path.relative(REPO_ROOT, file)}`);
    process.exitCode = 1;
    return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf8");
  console.warn(`[sync-versions] ✓ Updated ${path.relative(REPO_ROOT, file)}`);
  return true;
}

/**
 * @param {string} repoRoot
 * @param {string} catalogBlob
 * @param {boolean} checkOnly
 */
function updatePnpmWorkspaceCatalog(repoRoot, catalogBlob, checkOnly) {
  const wsPath = path.join(repoRoot, "pnpm-workspace.yaml");
  const raw = fs.readFileSync(wsPath, "utf8");
  const marker = /\n\s*catalog:[\s\S]*?(?=\n\S|$)/;
  const head = marker.test(raw) ? raw.replace(marker, "").trimEnd() : raw.trimEnd();
  const out = `${head}\n\n${catalogBlob}`;
  writeIfChanged(wsPath, out, checkOnly);
}

function main() {
  const checkOnly = process.argv.includes("--check");
  const manifest = loadManifest();

  const depsContent = renderDepsTs(manifest.pkg);
  writeIfChanged(DEPS_TS, depsContent, checkOnly);

  const pinsContent = renderPinsTs(manifest.packageManagers);
  writeIfChanged(PINS_TS, pinsContent, checkOnly);

  const catalogKeys = collectWorkspaceCatalogDeps(REPO_ROOT);
  /** @type {Record<string,string>} */
  const catalogSlice = {};
  for (const k of catalogKeys) {
    const v = manifest.mergedForCatalog[k];
    if (!v) {
      throw new Error(
        `[sync-versions] Workspace declares "${k}: catalog:" but no version exists in packages or repoOnly in versions.yaml.`,
      );
    }
    catalogSlice[k] = v;
  }

  /** @type {[string,string][]} */
  const sortedEntries = Object.entries(catalogSlice).sort(([a], [b]) => a.localeCompare(b));
  const catalogYamlTail = renderPnpmCatalogYaml(sortedEntries);
  updatePnpmWorkspaceCatalog(REPO_ROOT, catalogYamlTail, checkOnly);

  if (process.exitCode === 1) {
    console.error("[sync-versions] Run `pnpm sync-versions` locally to fix divergence.");
    process.exit(1);
  }
}

main();
