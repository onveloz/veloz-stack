#!/usr/bin/env node
/**
 * Globs every file under `templates/` and emits `src/templates.generated.ts`
 * as a Map<relativePath, content>. Matches the Better-T-Stack pattern: the
 * compiled CLI ends up with all template bodies embedded — zero disk reads
 * at runtime.
 *
 * Re-run: `node scripts/build-templates.mjs` (also triggered by `postinstall`).
 */
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const __dirname = import.meta.dirname;
const ROOT = join(__dirname, "..");
const SRC = join(ROOT, "templates");
const OUT = join(ROOT, "src", "templates.generated.ts");

async function walk(dir) {
  const entries = await readdir(dir);
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const p = join(dir, entry);
      const s = await stat(p);
      if (s.isDirectory()) {
        return walk(p);
      }
      return [p];
    }),
  );
  return nested.flat();
}

try {
  let files = [];
  try {
    files = await walk(SRC);
  } catch {
    console.warn(`[build-templates] no ${SRC} yet — emitting empty map`);
  }

  const entries = await Promise.all(
    files.map(async (abs) => {
      const rel = relative(SRC, abs).replaceAll("\\", "/");
      const content = await readFile(abs, "utf8");
      return `  [${JSON.stringify(rel)}, ${JSON.stringify(content)}],`;
    }),
  );

  const body = `// Auto-generated by scripts/build-templates.mjs — do not edit.
// Re-run via \`pnpm gen\` at packages/template-generator.

/** All embedded template bodies keyed by relative path under \`templates/\`. */
export const EMBEDDED_TEMPLATES = new Map<string, string>([
${entries.join("\n")}
]);

/** Count of entries in {@link EMBEDDED_TEMPLATES}. */
export const TEMPLATE_COUNT = ${entries.length};
`;

  await writeFile(OUT, body, "utf8");
  console.log(
    `[build-templates] wrote ${entries.length} templates → ${relative(ROOT, OUT)}`,
  );
} catch (error) {
  console.error(error);
  process.exit(1);
}
